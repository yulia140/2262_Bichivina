#include <iostream>

int main() {
    int a = 0;
    double b = 0.0;

    std::cout << "sizeof(int) = " << sizeof(int) << " bytes" << std::endl;
    std::cout << "sizeof(a) = " << sizeof(a) << " bytes" << std::endl;
    std::cout << "sizeof(b) = " << sizeof(b) << " bytes" << std::endl;

    return 0;
}